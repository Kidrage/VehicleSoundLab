"""Assemble the independently runnable project; evidence overlays use separate ZIPs."""
import argparse
import json
from pathlib import Path
import re
import shutil
from archive_evidence import ROOT, files_at, make_zip


def required(path):
    if not path.is_file():
        raise FileNotFoundError(path)
    return path


def main_files():
    files = set()
    for name in ("src", "tests", "modules", "experiments", "handoff", "research", "voices", "performances", "tools"):
        files.update(p for p in files_at(ROOT/name) if "python_deps" not in p.parts and ".git" not in p.parts)
    scripts = sorted(ROOT.glob("Launch*.cmd"))
    files.update(scripts)
    for name in ("AGENTS.md", "README.md", ".gitignore", "build.ps1", "Build-System.ps1", "CMakeLists.txt"):
        files.add(required(ROOT/name))
    release_dirs = {ROOT/"build-v015/Release"}
    for script in scripts:
        for raw in re.findall(r'%~dp0([^"\r\n]+\.(?:exe|model|ids))"', script.read_text(encoding="utf-8-sig"), re.I):
            p = ROOT/raw
            if p.name == "VslSystem.exe" and "handoff-build" in p.parts:
                continue
            files.add(required(p))
            if p.suffix.lower() == ".exe" and p.parent.name == "Release":
                release_dirs.add(p.parent)
    for folder in release_dirs:
        files.update(p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in (".exe", ".lib", ".dll"))
    for name in ("approval_manifest.json", "segments_v1.json"):
        files.add(required(ROOT/"references"/name))
    for name in ("src/io/wav.h", "bin/vsl_core.lib"):
        files.add(required(ROOT/"baselines/v0.20.0"/name))
    analysis = ROOT/"references/analysis"
    clips = {
        "osc_quality_v1": ("band_only_audition.wav", "legacy64_audition.wav"),
        "osc_quality_v2": ("rank64_audition.wav", "complete_audition.wav", "rank16_audition.wav"),
        "detail_modulation_v1": ("detail075_audition.wav", "detail100_audition.wav", "listening/detail100_radial_audition.wav"),
        "low_body_v1/renders": ("bass000_audition.wav", "bass050_audition.wav", "bass100_audition.wav", "body_solo_audition.wav"),
        "low_rumble_v2": ("all_sources_lf.png", "procedural_lf_spectra.png", "renders/old_three_tone_same_DNA.wav"),
        "low_rumble_v2/references": (
            "A_exterior_blips_low25_280.wav", "B_cabin_pull_low25_280.wav",
            "D_dyno_gears_context_low25_280.wav", "E_sport_context_low25_280.wav"),
    }
    for folder, names in clips.items():
        files.update(required(analysis/folder/name) for name in names)
    for voice in ("A Exterior", "B Cabin", "D Dyno", "E Cabin"):
        for tag in ("mix000", "mix040", "mix060", "mix080", "mix100", "solo"):
            files.add(required(analysis/"low_rumble_v2/renders"/f"{voice}_{tag}_audition.wav"))
    return sorted(files)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    out = args.destination.resolve()
    stage = out/"VehicleSoundLab"
    archive = out/"01-system.zip"
    if archive.exists() or stage.exists():
        raise FileExistsError(f"{archive} or {stage}")
    paths = main_files()
    stage.mkdir(parents=True)
    for p in paths:
        dest = stage/p.relative_to(ROOT)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, dest)
    # Test logs and temporary files generated by the new build are never staged.
    result = make_zip(stage, [stage/p.relative_to(ROOT) for p in paths], archive)
    (out/"system-index.json").write_text(json.dumps(result, indent=2)+"\n", encoding="utf-8")


if __name__ == "__main__":
    main()

