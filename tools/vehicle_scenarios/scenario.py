"""Pedal-only scenarios over the existing unique C vehicle controller."""
from copy import deepcopy

from vehicle_controller import take

RATE = 48000
LIFECYCLE = ('OFF', 'READY', 'CRANK', 'CATCH', 'RUNNING', 'STOPPING')
OPERATING = ('IDLE', 'FREE_REV', 'PULL', 'CRUISE', 'OVERRUN',
             'SHIFT_CUT', 'SHIFT_RECOVER', 'REV_MATCH')


def sport_lifecycle(bridge, selection=0, event_overrides=None, control=None,startup_response=None,event_policy=None,dna_bank=None):
    """A full start/drive/lift/brake/idle/stop cycle, with no authored RPM."""
    provided = control is not None
    control = deepcopy(control) if provided else bridge.initial(selection,dna_bank)[0]
    control.update(mode=1, ignition=0, start_id=0, throttle=0., brake=.65,
                   automatic=1, gear=1)
    if not provided:
        control['backfire'] = 1
    control['input'].update(source=0, valid=0, sequence=0, speed_mps=0.,
                            acceleration_mps2=0., tire_slip=0.)
    control['events']['manual_sequence'] = 0
    if not provided:
        control['events']['enabled'] = 1
    value = take.create(bridge, selection, control, event_overrides,startup_response,event_policy,dna_bank)
    instructions = [
        (0., 'OFF', {}, 'Engine off, listener not started automatically.'),
        (.35, 'START', dict(ignition=1, start_id=1), 'One explicit start edge.'),
        (2.5, 'LAUNCH', dict(throttle=.20, brake=0.), 'Release brake, gentle pedal.'),
        (3.2, 'ACCELERATE', dict(throttle=.92), 'Sport automatic upshifts.'),
        (15.5, 'LIFT', dict(throttle=0.), 'Lift holds gear; qualify overrun.'),
        (18., 'BRAKE', dict(brake=.85), 'Braking permits safe downshifts.'),
        (27., 'STOPPED_IDLE', dict(brake=.65, automatic=0, gear=0),
         'Neutral while stopped; allow idle timbre to settle.'),
        (29.5, 'IGNITION_OFF', dict(ignition=0), 'Stop engine, keep monitoring tail.'),
        (32., 'END', {}, 'End after stop and release tails.'),
    ]
    stages = []
    for seconds, name, changes, note in instructions:
        control.update(changes)
        frame = round(seconds * RATE)
        if 0 < seconds < 32:
            take.append(value, frame, control)
        stages.append(dict(frame=frame, seconds=seconds, name=name,
                           control=deepcopy(control), note=note))
    value['frames'] = 32 * RATE
    return value, dict(schema='vsl.vehicle-scenario/1', name='sport_lifecycle',
                       sample_rate=RATE, stages=stages,
                       trajectory='RPM, speed, load and shifting are generated by C, not prescribed.',
                       timbre_accepted=False, goal_complete=False)
