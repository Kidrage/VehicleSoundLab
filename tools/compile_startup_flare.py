"""Freeze the selected catch gesture as C parameters, never recorded PCM.

Run from the repository root. Input SHA checks precede deterministic generation.
Only FIR spectral colour, 48 moving oscillators and coarse envelopes are copied.
"""
import hashlib
import json
from pathlib import Path


def generate(repo):
    folder=repo/'experiments/startup_character_v1/runtime_bank'
    bank_path=folder/'bank.json'
    manifest=json.loads((folder/'manifest.json').read_text(encoding='utf-8'))
    hashes={row['path']:row['sha256'] for row in manifest}
    if hashlib.sha256(bank_path.read_bytes()).hexdigest()!=hashes['bank.json']:
        raise ValueError('Startup bank identity mismatch')
    bank=json.loads(bank_path.read_text(encoding='utf-8'));model=bank['profiles']['catch']
    def number(x):return format(float(x),'.17g')
    def vector(values):return '{'+','.join(map(number,values))+'}'
    lines=['/* Generated by tools/compile_startup_flare.py; source-conditioned parameters, no PCM. */',
           '#include "model.h"','#include <stdlib.h>','#include <string.h>']
    profiles=[]
    for k,row in enumerate(model['profiles']):
        data=(folder/row['path']).read_bytes()
        if hashlib.sha256(data).hexdigest()!=row['sha256']:raise ValueError('FIR identity mismatch')
        tokens=iter(data.decode('ascii').split())
        assert next(tokens)=='VSL_SPECTRAL_TEXTURE' and int(next(tokens))==1
        rate,count,warmup=(int(next(tokens)) for _ in range(3));bands=[]
        for j in range(count):
            length=int(next(tokens));gain=float(next(tokens));ratio=float(next(tokens))
            taps=[float(next(tokens)) for _ in range(length)];bands.append((length,gain,ratio))
            lines.append(f'static const double taps_{k}_{j}[{length}]={{')
            lines.extend('    '+','.join(map(number,taps[n:n+6]))+',' for n in range(0,length,6))
            lines.append('};')
        assert next(tokens,None) is None
        profiles.append((rate,count,warmup,bands))
    lines.append('static const ScRidge ridges[]={')
    for row in model['ridges']:
        lines.append('    {'+f"{row['start_frame']},{row['frames']},{number(row['hz'])},{number(row['slew_hz_per_second'])},"+
                     vector(row['amplitude'])+','+vector(row['phase'])+'},')
    lines+=['};','ScVoice *sfl_model_create(void){',
            '    SfProfile *storage=calloc(3,sizeof *storage);const SfProfile *profiles[3];ScVoice *v;unsigned k;',
            '    static const double envelope[9]='+vector(model['envelope'])+';',
            '    if(!storage)return NULL;']
    for k,(rate,count,warmup,bands) in enumerate(profiles):
        lines.append(f'    storage[{k}].rate={rate};storage[{k}].count={count};storage[{k}].warmup_frames={warmup};')
        for j,(length,gain,ratio) in enumerate(bands):
            lines.append(f'    storage[{k}].band[{j}].count={length};storage[{k}].band[{j}].gain={number(gain)};storage[{k}].band[{j}].right_over_left={number(ratio)};')
            lines.append(f'    memcpy(storage[{k}].band[{j}].taps,taps_{k}_{j},sizeof taps_{k}_{j});')
    lines+=['    for(k=0;k<3;++k)profiles[k]=storage+k;',
            f"    v=sc_create(profiles,envelope,{number(model['variation'])},UINT64_C(98355));free(storage);",
            '    if(!v)return NULL;',
            f"    if(!sc_set_ridges(v,ridges,{len(model['ridges'])},{model['reference_frames']},{number(model['ridge_variation'])},{number(model['ridge_pitch'])},UINT64_C(98355))){{sc_destroy(v);return NULL;}}",
            '    /* Match the selected first catch\'s silent procedural history, non-RT. */',
            '    for(k=0;k<91680;++k){double out[2];if(!sc_tick_expression(v,0,0,0.12243746163707875,.82,1.15,.95,out)){sc_destroy(v);return NULL;}}',
            '    return v;','}']
    target=repo/'modules/startup_flare/model.c';target.parent.mkdir(exist_ok=True)
    target.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(target)


if __name__=='__main__':generate(Path(__file__).resolve().parents[1])
